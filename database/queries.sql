-- Query 3: Comprehensive Booking Details with Customer, Venue, and Package Info
-- Topic: Multi-table INNER & LEFT JOINs
SELECT 
    b.booking_reference,
    b.wedding_date,
    u.full_name AS customer_name,
    u.phone AS customer_phone,
    v.name AS venue_name,
    v.city AS venue_city,
    COALESCE(p.name, 'Custom Package') AS package_name,
    b.guest_count,
    b.total_amount,
    b.paid_amount,
    b.status
FROM bookings b
JOIN users u ON b.customer_id = u.id
LEFT JOIN venues v ON b.venue_id = v.id
LEFT JOIN packages p ON b.package_id = p.id
ORDER BY b.wedding_date ASC;

-- Query 4: Detailed Breakdown of Vendor Services Booked per Wedding Event
-- Topic: 4-Table Join connecting Bookings -> Booking_Services -> Vendor_Services -> Vendors
SELECT 
    b.booking_reference,
    b.wedding_date,
    vn.business_name AS vendor_name,
    vn.category AS vendor_category,
    vs.custom_title AS service_title,
    bs.quantity,
    bs.price_at_booking,
    (bs.quantity * bs.price_at_booking) AS subtotal
FROM bookings b
JOIN booking_services bs ON b.id = bs.booking_id
JOIN vendor_services vs ON bs.vendor_service_id = vs.id
JOIN vendors vn ON vs.vendor_id = vn.id
ORDER BY b.booking_reference, subtotal DESC;

-- Query 5: Venues That Have Never Been Booked (Unused Inventory)
-- Topic: LEFT OUTER JOIN with NULL check
SELECT 
    v.id,
    v.name,
    v.city,
    v.venue_type,
    v.price_per_day
FROM venues v
LEFT JOIN bookings b ON v.id = b.venue_id
WHERE b.id IS NULL;

-- ----------------------------------------------------------------------------
-- CATEGORY 3: AGGREGATIONS, GROUP BY & HAVING
-- ----------------------------------------------------------------------------

-- Query 6: Revenue Generated by Each Venue Having at Least 1 Booking
-- Topic: GROUP BY, SUM, COUNT, HAVING
SELECT 
    v.id AS venue_id,
    v.name AS venue_name,
    v.city,
    COUNT(b.id) AS total_events,
    SUM(b.total_amount) AS gross_revenue,
    ROUND(AVG(b.guest_count), 0) AS average_guests
FROM venues v
JOIN bookings b ON v.id = b.venue_id
GROUP BY v.id, v.name, v.city
HAVING COUNT(b.id) >= 1
ORDER BY gross_revenue DESC;

-- Query 7: Total Earnings and Number of Orders Fulfilled by Each Vendor
-- Topic: Multi-table Aggregation with COALESCE
SELECT 
    vn.id AS vendor_id,
    vn.business_name,
    vn.category,
    COUNT(bs.id) AS total_services_booked,
    COALESCE(SUM(bs.quantity * bs.price_at_booking), 0) AS total_revenue
FROM vendors vn
LEFT JOIN vendor_services vs ON vn.id = vs.vendor_id
LEFT JOIN booking_services bs ON vs.id = bs.vendor_service_id
GROUP BY vn.id, vn.business_name, vn.category
ORDER BY total_revenue DESC;

-- Query 8: Payment Methods Breakdown and Transaction Success Rates
-- Topic: Conditional Aggregation (CASE WHEN inside SUM/COUNT)
SELECT 
    payment_method,
    COUNT(id) AS total_transactions,
    SUM(CASE WHEN payment_status = 'completed' THEN amount ELSE 0 END) AS successful_amount,
    COUNT(CASE WHEN payment_status = 'completed' THEN 1 END) AS successful_count,
    ROUND(
        (COUNT(CASE WHEN payment_status = 'completed' THEN 1 END)::NUMERIC / COUNT(id)::NUMERIC) * 100, 
        2
    ) AS success_rate_pct
FROM payments
GROUP BY payment_method
ORDER BY successful_amount DESC;

