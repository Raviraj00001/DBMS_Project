-- Query 13: Rank Venues within Each Venue Type by Daily Rental Price
-- Topic: DENSE_RANK() OVER (PARTITION BY ... ORDER BY ...)
SELECT 
    id,
    name,
    venue_type,
    city,
    price_per_day,
    DENSE_RANK() OVER (
        PARTITION BY venue_type 
        ORDER BY price_per_day DESC
    ) AS rank_within_type
FROM venues;

-- Query 14: Cumulative Payment Received Timeline (Running Total)
-- Topic: Window Function SUM() OVER with Running Total
SELECT 
    id AS payment_id,
    transaction_reference,
    booking_id,
    amount,
    payment_date,
    SUM(amount) OVER (
        ORDER BY payment_date ASC 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS cumulative_platform_revenue
FROM payments
WHERE payment_status = 'completed';

-- Query 15: Identify Top 2 Most Expensive Packages per Guest Capacity Tier
-- Topic: ROW_NUMBER() with CTE (Common Table Expression)
WITH RankedPackages AS (
    SELECT 
        id,
        name,
        tier,
        guest_count,
        base_price,
        ROW_NUMBER() OVER (
            PARTITION BY tier 
            ORDER BY base_price DESC
        ) AS rank_in_tier
    FROM packages
)
SELECT * FROM RankedPackages WHERE rank_in_tier <= 2;

