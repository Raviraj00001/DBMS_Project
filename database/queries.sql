-- Query 1: Retrieve all active luxury venues with capacity greater than 400 guests
-- Topic: Basic SELECT, WHERE clause, ORDER BY
SELECT 
    id, name, city, venue_type, capacity_min, capacity_max, price_per_day, rating
FROM venues
WHERE is_available = TRUE 
  AND capacity_max >= 400
ORDER BY price_per_day DESC;

-- Query 2: Find all verified vendors specializing in catering or photography
-- Topic: IN operator, Boolean filters
SELECT 
    id, business_name, category, city, experience_years, starting_price, rating
FROM vendors
WHERE is_verified = TRUE 
  AND category IN ('catering', 'photography')
ORDER BY rating DESC, experience_years DESC;

