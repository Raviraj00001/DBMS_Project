-- Query 9: Customers Who Have Spent More Than the Overall Average Booking Value
-- Topic: Non-correlated Subquery with AVG in WHERE
SELECT 
    u.id,
    u.full_name,
    u.email,
    b.booking_reference,
    b.total_amount
FROM users u
JOIN bookings b ON u.id = b.customer_id
WHERE b.total_amount > (
    SELECT AVG(total_amount) FROM bookings
)
ORDER BY b.total_amount DESC;

-- Query 10: Venues Priced Higher Than the Average Venue Price in Their Respective State
-- Topic: Correlated Subquery
SELECT 
    v1.id,
    v1.name,
    v1.city,
    v1.state,
    v1.price_per_day,
    (SELECT ROUND(AVG(v2.price_per_day), 2) FROM venues v2 WHERE v2.state = v1.state) AS state_average_price
FROM venues v1
WHERE v1.price_per_day >= (
    SELECT AVG(v2.price_per_day)
    FROM venues v2
    WHERE v2.state = v1.state
);

-- Query 11: Customers with Active Bookings Using EXISTS Operator
-- Topic: EXISTS Correlated Subquery
SELECT 
    u.id, 
    u.full_name, 
    u.email, 
    u.phone
FROM users u
WHERE EXISTS (
    SELECT 1 
    FROM bookings b 
    WHERE b.customer_id = u.id 
      AND b.status IN ('pending', 'confirmed')
);

-- Query 12: Vendors with No Services Listed Yet
-- Topic: NOT IN Subquery
SELECT 
    id, business_name, category, city
FROM vendors
WHERE id NOT IN (
    SELECT DISTINCT vendor_id FROM vendor_services
);

