-- Query 16: Complete Financial Health Audit (Outstanding Balances per Customer)
-- Topic: Multi-CTE Query with Aggregate Joining
WITH BookingTotals AS (
    SELECT 
        customer_id,
        COUNT(id) AS total_bookings_count,
        SUM(total_amount) AS total_contract_value,
        SUM(paid_amount) AS total_settled_value
    FROM bookings
    GROUP BY customer_id
),
CustomerSummary AS (
    SELECT 
        u.id AS customer_id,
        u.full_name,
        u.email,
        u.phone,
        bt.total_bookings_count,
        bt.total_contract_value,
        bt.total_settled_value,
        (bt.total_contract_value - bt.total_settled_value) AS outstanding_due
    FROM users u
    JOIN BookingTotals bt ON u.id = bt.customer_id
)
SELECT * 
FROM CustomerSummary
ORDER BY outstanding_due DESC;

-- Query 17: Package Popularity and Service Attachment Count
-- Topic: CTE with multi-tier joining
WITH PackageUsage AS (
    SELECT 
        p.id AS package_id,
        p.name AS package_name,
        p.tier,
        p.base_price,
        COUNT(b.id) AS bookings_count,
        COALESCE(SUM(b.total_amount), 0) AS total_revenue
    FROM packages p
    LEFT JOIN bookings b ON p.id = b.package_id
    GROUP BY p.id, p.name, p.tier, p.base_price
),
ServiceInclusions AS (
    SELECT 
        package_id,
        COUNT(service_id) AS included_services_count
    FROM package_services
    GROUP BY package_id
)
SELECT 
    pu.*,
    COALESCE(si.included_services_count, 0) AS included_services
FROM PackageUsage pu
LEFT JOIN ServiceInclusions si ON pu.package_id = si.package_id
ORDER BY pu.bookings_count DESC, pu.total_revenue DESC;

